-- Ranking Queries (Window Functions)
-- Rank States by Sales
SELECT
	STATE,
	SUM(SALES) AS SALES,
	RANK() OVER (
		ORDER BY
			SUM(SALES) DESC
	) AS SALES_RANK
FROM
	SUPERSTORE GROUP BY
	STATE;
	
-- Dense Rank States by Profit
SELECT
	STATE,
	SUM(PROFIT) AS PROFIT,
	DENSE_RANK() OVER (
		ORDER BY
			SUM(PROFIT) DESC
	) AS PROFIT_RANK
FROM
	SUPERSTORE GROUP BY
	STATE;
	
-- Rank Categories by Profit
SELECT
	CATEGORY,
	SUM(PROFIT) AS PROFIT,
	RANK() OVER (
		ORDER BY
			SUM(PROFIT) DESC
	) AS CATEGORY_RANK
FROM
	SUPERSTORE GROUP BY
	CATEGORY;


-- CASE Statement Queries
-- Profit Status
SELECT
	CATEGORY,
	PROFIT,
	CASE
		WHEN PROFIT > 0 THEN 'Profit'
		WHEN PROFIT < 0 THEN 'Loss'
		ELSE 'No Profit'
	END AS STATUS FROM
	SUPERSTORE;
	
-- Discount Level
SELECT
	DISCOUNT,
	CASE
		WHEN DISCOUNT = 0 THEN 'No Discount'
		WHEN DISCOUNT <= 0.20 THEN 'Low'
		WHEN DISCOUNT <= 0.50 THEN 'Medium'
		ELSE 'High'
	END AS DISCOUNT_LEVEL
FROM
	SUPERSTORE;


-- Advanced Aggregation
-- Region-wise Profit Margin
SELECT
	REGION,
	SUM(SALES) AS SALES,
	SUM(PROFIT) AS PROFIT,
	ROUND((SUM(PROFIT) / SUM(SALES)) * 100, 2) AS PROFIT_MARGIN
FROM
	SUPERSTORE GROUP BY
	REGION;

-- Category-wise Profit Margin
SELECT
	CATEGORY,
	SUM(SALES) AS SALES,
	SUM(PROFIT) AS PROFIT,
	ROUND((SUM(PROFIT) / SUM(SALES)) * 100, 2) AS PROFIT_MARGIN
FROM
	SUPERSTORE
GROUP BY
	CATEGORY;
	
-- Overall Business Summary
